import 'dart:math';
import 'dart:typed_data';

import 'package:crypto/crypto.dart' as crypto;

/// A pure-Dart implementation of the XEdDSA signature scheme
/// (https://signal.org/docs/specifications/xeddsa), used by real-world
/// legacy-OMEMO clients (Conversations/Gajim/Dino, all libsignal-based) to
/// sign their signed-prekey (SPK) with their Curve25519 (X25519) identity
/// key, instead of a genuine Ed25519 keypair.
///
/// Background: `omemo_dart` (see `vendor/omemo_dart/`) was built for
/// OMEMO2, where identity keys are real Ed25519 keypairs, and has no
/// concept of XEdDSA at all. For legacy OMEMO (XEP-0384 v0.3.0) to
/// interoperate with real clients, *our own* identity key must be a
/// genuine X25519 keypair (see `OmemoBackend._loadOrGenerateDevice` /
/// `_generateLegacyDevice`), and our SPK signature must be produced with
/// [xeddsaSign] below so that real clients -- who convert our raw X25519
/// identity-key bytes to the birationally-equivalent Edwards point via
/// `convert_mont` and then do a standard Ed25519 verify -- can verify it.
///
/// Conversely, *verifying* a signature made by a real client only needs
/// the Montgomery -> Edwards conversion (`convert_mont`, implemented as
/// `convertMontgomeryToEdwards` in `vendor/omemo_dart/lib/src/xeddsa_convert.dart`,
/// since it is needed inside the vendored library itself -- see
/// `vendor/omemo_dart/VENDORING.md`) followed by a standard Ed25519
/// verify (`package:cryptography`'s `Ed25519().verify`); no point
/// arithmetic is required for verification, so that half of XEdDSA isn't
/// duplicated here.
///
/// This file implements the *other* half -- signing -- which needs actual
/// Edwards25519 point/scalar arithmetic (`calculate_key_pair`), since the
/// signing scalar must be derived from the already-clamped Curve25519
/// private scalar directly (not via `package:cryptography`'s normal
/// `Ed25519.newKeyPairFromSeed`, which hashes a *seed* with SHA-512 to
/// derive its own scalar -- XEdDSA instead treats the raw Montgomery
/// scalar itself as the (possibly negated) Edwards scalar). No existing
/// Dart package was found exposing this lower-level primitive (checked
/// `package:cryptography`'s public API), so it is implemented here from
/// first principles using `BigInt`-based field arithmetic and an extended
/// twisted-Edwards point representation. Performance is not a concern:
/// this is only used when generating/rotating our own legacy-OMEMO
/// device's SPK signature, not on any hot path.

/// The Curve25519/Ed25519 field prime, `p = 2^255 - 19`.
final BigInt kFieldPrime = BigInt.two.pow(255) - BigInt.from(19);

/// The order of the (prime-order) subgroup generated by the Ed25519 base
/// point, `q = 2^252 + 27742317777372353535851937790883648493`.
final BigInt kGroupOrder =
    BigInt.two.pow(252) + BigInt.parse('27742317777372353535851937790883648493');

/// The twisted Edwards curve parameter `d = -121665/121666 (mod p)`.
final BigInt _kCurveD = _fieldDiv(-BigInt.from(121665), BigInt.from(121666));

/// The standard Ed25519 base point `B`, as canonical (x, y) affine
/// coordinates. Per the XEdDSA spec, `B = convert_mont(9)`, i.e. this is
/// the same point as the birational-map image of the X25519 base point.
final BigInt _kBaseX = BigInt.parse(
  '15112221349535400772501151409588531511454012693041857206046113283949847762202',
);
final BigInt _kBaseY = BigInt.parse(
  '46316835694926478169428394003475163141307993866256225615783033603165251855960',
);

BigInt _mod(BigInt a, BigInt m) {
  final r = a % m;
  return r.isNegative ? r + m : r;
}

BigInt _fieldMod(BigInt a) => _mod(a, kFieldPrime);
BigInt _groupMod(BigInt a) => _mod(a, kGroupOrder);

BigInt _fieldInv(BigInt a) => a.modPow(kFieldPrime - BigInt.two, kFieldPrime);

BigInt _fieldDiv(BigInt a, BigInt b) =>
    _fieldMod(_fieldMod(a) * _fieldInv(_fieldMod(b)));

BigInt _decodeLittleEndian(List<int> bytes) {
  var result = BigInt.zero;
  for (var i = bytes.length - 1; i >= 0; i--) {
    result = (result << 8) | BigInt.from(bytes[i] & 0xff);
  }
  return result;
}

Uint8List _encodeLittleEndian(BigInt value, int length) {
  final bytes = Uint8List(length);
  var v = value;
  final mask = BigInt.from(0xff);
  for (var i = 0; i < length; i++) {
    bytes[i] = (v & mask).toInt();
    v = v >> 8;
  }
  return bytes;
}

/// A point on the twisted Edwards curve `-x^2 + y^2 = 1 + d*x^2*y^2`, in
/// extended homogeneous coordinates `(X, Y, Z, T)` with `x = X/Z`,
/// `y = Y/Z`, `x*y = T/Z`, per [Hisil-Wong-Carter-Dawson 2008].
class _EdPoint {
  const _EdPoint(this.x, this.y, this.z, this.t);

  final BigInt x;
  final BigInt y;
  final BigInt z;
  final BigInt t;

  static final _EdPoint identity = _EdPoint(
    BigInt.zero,
    BigInt.one,
    BigInt.one,
    BigInt.zero,
  );

  static final _EdPoint base = _EdPoint(
    _fieldMod(_kBaseX),
    _fieldMod(_kBaseY),
    BigInt.one,
    _fieldMod(_kBaseX * _kBaseY),
  );

  /// Point addition using the "add-2008-hwcd-3" formulas for `a = -1`
  /// twisted Edwards curves. Also correct (if not optimal) for doubling
  /// (i.e. `this == other`).
  _EdPoint operator +(_EdPoint other) {
    final a = _fieldMod((y - x) * (other.y - other.x));
    final b = _fieldMod((y + x) * (other.y + other.x));
    final c = _fieldMod(t * BigInt.two * _kCurveD * other.t);
    final d = _fieldMod(z * BigInt.two * other.z);
    final e = _fieldMod(b - a);
    final f = _fieldMod(d - c);
    final g = _fieldMod(d + c);
    final h = _fieldMod(b + a);
    return _EdPoint(
      _fieldMod(e * f),
      _fieldMod(g * h),
      _fieldMod(f * g),
      _fieldMod(e * h),
    );
  }

  /// Scalar multiplication via double-and-add, MSB to LSB. [scalar] must
  /// be non-negative.
  _EdPoint scalarMultiply(BigInt scalar) {
    var result = identity;
    var addend = this;
    var k = scalar;
    while (k > BigInt.zero) {
      if (k.isOdd) {
        result = result + addend;
      }
      addend = addend + addend;
      k = k >> 1;
    }
    return result;
  }

  /// Encodes this point as the standard 32-byte little-endian Ed25519
  /// public-key encoding: the `y` coordinate in little-endian form, with
  /// the sign of `x` stored in the otherwise-unused top bit.
  Uint8List encode() {
    final zInv = _fieldInv(z);
    final affineX = _fieldMod(x * zInv);
    final affineY = _fieldMod(y * zInv);
    final encoded = _encodeLittleEndian(affineY, 32);
    if (affineX.isOdd) {
      encoded[31] |= 0x80;
    } else {
      encoded[31] &= 0x7f;
    }
    return encoded;
  }

  /// The sign bit (bit 255) that [encode] would produce, i.e. whether the
  /// affine `x` coordinate is odd.
  int get signBit {
    final zInv = _fieldInv(z);
    final affineX = _fieldMod(x * zInv);
    return affineX.isOdd ? 1 : 0;
  }
}

/// Clamps a raw 32-byte Curve25519 private key per the X25519 convention
/// (RFC 7748 §5): clear the low 3 bits and the highest bit, and set the
/// second-highest bit. Real legacy-OMEMO clients' stored private keys are
/// the raw (pre-clamp) 32 random bytes; [calculateKeyPair]/[xeddsaSign]
/// expect the same raw form and clamp internally, matching libsignal's
/// own `Curve25519.generateKeyPair`/XEdDSA implementation.
Uint8List clampScalarBytes(List<int> rawPrivateKey) {
  final clamped = Uint8List.fromList(rawPrivateKey);
  clamped[0] &= 248;
  clamped[31] &= 127;
  clamped[31] |= 64;
  return clamped;
}

/// Computes `y = (u - 1) / (u + 1) (mod p)`, the birational map from a
/// Montgomery-form Curve25519 public key's `u` coordinate to the `y`
/// coordinate of the corresponding twisted-Edwards point, and encodes the
/// result as a standard 32-byte Ed25519 public key with the requested
/// [sign] bit (0 by convention for XEdDSA verification, i.e.
/// `convert_mont(u)` in the spec).
///
/// This is also implemented, independently, as
/// `convertMontgomeryToEdwards` in
/// `vendor/omemo_dart/lib/src/xeddsa_convert.dart`, since the vendored
/// `omemo_dart` library needs it internally (for converting a remote
/// legacy-OMEMO contact's incoming `<key kex="true">` identity key) and
/// cannot depend on this app-level file. [convertMontgomeryToEdwards]
/// here re-exposes the same math for use/testing from application code
/// (e.g. cross-checking [xeddsaSign]'s output), and a dedicated unit test
/// (`test/xeddsa_test.dart`) asserts both implementations agree.
Uint8List convertMontgomeryToEdwards(List<int> uBytes, {int sign = 0}) {
  assert(uBytes.length == 32, 'u must be a 32-byte Curve25519 coordinate');
  final u = _fieldMod(_decodeLittleEndian(uBytes));
  final y = _fieldDiv(u - BigInt.one, u + BigInt.one);
  final encoded = _encodeLittleEndian(y, 32);
  if (sign & 1 == 1) {
    encoded[31] |= 0x80;
  } else {
    encoded[31] &= 0x7f;
  }
  return encoded;
}

/// The result of [calculateKeyPair]: the Edwards signing scalar `a` (32
/// bytes, little-endian, reduced mod [kGroupOrder]) and its corresponding
/// Edwards public key `A` (32 bytes, standard Ed25519 encoding, always
/// with sign bit 0).
class XEdDSAKeyPair {
  const XEdDSAKeyPair(this.a, this.edwardsPublicKey);

  /// The (possibly negated) Edwards private scalar, little-endian.
  final Uint8List a;

  /// The Edwards public key `A`, standard 32-byte Ed25519 encoding.
  final Uint8List edwardsPublicKey;
}

/// Implements XEdDSA's `calculate_key_pair(k)`: given a raw (unclamped)
/// Curve25519 private key [k], derives the Edwards keypair `(a, A)` to be
/// used for signing/verification, per
/// https://signal.org/docs/specifications/xeddsa:
///
/// ```
/// E = kB
/// A.y = E.y; A.s = 0
/// if E.s == 1: a = -k (mod q) else a = k (mod q)
/// ```
///
/// Because point negation on a twisted Edwards curve negates `x` (and
/// hence the sign bit) while preserving `y`, `A` always ends up with sign
/// bit 0 -- matching the `convert_mont(u, sign=0)` convention used by
/// verifiers (see [convertMontgomeryToEdwards]).
XEdDSAKeyPair calculateKeyPair(List<int> k) {
  final clamped = clampScalarBytes(k);
  final scalar = _decodeLittleEndian(clamped);
  final e = _EdPoint.base.scalarMultiply(scalar);
  final a = e.signBit == 1 ? _groupMod(-scalar) : _groupMod(scalar);
  final bigA = _EdPoint.base.scalarMultiply(a);
  return XEdDSAKeyPair(
    _encodeLittleEndian(a, 32),
    bigA.encode(),
  );
}

/// `hash_i(X) = SHA-512((2b - 1 - i repeated as a b/8-byte prefix) || X)`,
/// per the XEdDSA spec's domain-separated hash family (`b = 256`, so the
/// prefix is 32 bytes of `0xFF - i`). Returns the raw 64-byte SHA-512
/// digest (reduction mod [kGroupOrder] happens separately, see
/// [_hashToScalar]).
List<int> _domainSeparatedHash(int i, List<int> input) {
  final prefixByte = 0xFF - i;
  final prefixed = <int>[...List.filled(32, prefixByte), ...input];
  return crypto.sha512.convert(prefixed).bytes;
}

BigInt _hashToScalar(List<int> digest) => _groupMod(_decodeLittleEndian(digest));

/// Implements XEdDSA's `xeddsa_sign(k, M, Z)`:
///
/// ```
/// A, a = calculate_key_pair(k)
/// r = hash1(a || M || Z) (mod q)
/// R = rB
/// h = hash(R || A || M) (mod q)
/// s = r + ha (mod q)
/// return R || s
/// ```
///
/// [k] is our raw (unclamped) Curve25519 private key (e.g.
/// `OmemoDevice.ik.sk`'s bytes for the legacy-OMEMO backend), [message] is
/// the data to sign (the DJB-type-prefixed SPK bytes, matching
/// `OmemoBundle.spkSignatureMessage`'s convention -- see
/// `vendor/omemo_dart/VENDORING.md`), and [random] is 64 bytes of
/// cryptographically-secure randomness (generated internally via
/// `dart:math`'s `Random.secure()` if omitted; exposed as a parameter
/// purely so tests can supply fixed bytes for reproducibility).
///
/// Returns the 64-byte signature `R || s`. The resulting signature is a
/// standard, valid Ed25519 signature over `M` for the Edwards public key
/// `A = convert_mont(curve25519_pubkey(k))` -- i.e.
/// `Ed25519().verify(M, signature: Signature(sig, publicKey: A))` using
/// `package:cryptography` succeeds, which is exactly how real
/// legacy-OMEMO clients (Conversations/Gajim/Dino) verify our SPK
/// signature.
Uint8List xeddsaSign(List<int> k, List<int> message, {List<int>? random}) {
  final z = random ?? _secureRandomBytes(64);
  assert(z.length == 64, 'Z must be 64 bytes of randomness');

  final keyPair = calculateKeyPair(k);
  final a = _decodeLittleEndian(keyPair.a);

  final rDigest = _domainSeparatedHash(
    1,
    <int>[...keyPair.a, ...message, ...z],
  );
  final r = _hashToScalar(rDigest);
  final bigR = _EdPoint.base.scalarMultiply(r);
  final encodedR = bigR.encode();

  final hDigest =
      crypto.sha512.convert(<int>[...encodedR, ...keyPair.edwardsPublicKey, ...message]).bytes;
  final h = _hashToScalar(hDigest);

  final s = _groupMod(r + h * a);
  final encodedS = _encodeLittleEndian(s, 32);

  return Uint8List.fromList(<int>[...encodedR, ...encodedS]);
}

final Random _secureRandom = Random.secure();

Uint8List _secureRandomBytes(int length) {
  final bytes = Uint8List(length);
  for (var i = 0; i < length; i++) {
    bytes[i] = _secureRandom.nextInt(256);
  }
  return bytes;
}
